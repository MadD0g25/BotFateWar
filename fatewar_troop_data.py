def calculate_max_trainable(army_id, barrack_level, available_resources):
    """Calcule directement la quantite maximale entrainable, sans avoir
    besoin de tatonner par essais reseau successifs. Combine deux
    contraintes independantes :
    1. La capacite de la file d'attente de la caserne (BARRACK_TRAINING_CAPACITY),
       identique quel que soit le type de troupe.
    2. Les ressources disponibles / cout par unite (TROOP_RESOURCE_COSTS).

    available_resources : dict {res_type: quantite_disponible}, typiquement
    le retour de get_city_resources() une fois converti sur les memes
    codes de type que TROOP_RESOURCE_COSTS (2,3,4,5,16,17).

    Retourne le plus petit des deux plafonds (int), ou None si army_id
    ou barrack_level sont inconnus.

    ATTENTION : ce calcul utilise les couts BRUTS du fichier de
    configuration - des bonus actifs (technologies, VIP, evenements) qui
    reduisent le cout reel ne sont pas pris en compte ici, donc la vraie
    limite en jeu peut etre LEGEREMENT plus haute que ce calcul. A
    utiliser comme un point de depart fiable, pas une garantie absolue -
    reste utile de garder un essai reseau de secours en cas d'echec."""
    costs = TROOP_RESOURCE_COSTS.get(army_id)
    if costs is None:
        return None

    queue_cap = BARRACK_TRAINING_CAPACITY.get(barrack_level)
    if queue_cap is None:
        # Niveau au-dela de notre table (max 30 connu) - pas de plafond
        # connu de ce cote, on se base uniquement sur les ressources.
        queue_cap = float("inf")

    resource_cap = float("inf")
    for res_type, cost_per_unit in costs.items():
        if cost_per_unit <= 0:
            continue
        available = available_resources.get(res_type, 0)
        max_from_this_resource = available // cost_per_unit
        resource_cap = min(resource_cap, max_from_this_resource)

    result = min(queue_cap, resource_cap)
    if result == float("inf"):
        return None
    return int(result)


