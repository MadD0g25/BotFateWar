    # on cherche donc la cle correspondant a current_level+1.
    target_level = current_level + 1
    key = str(building_type) + "_" + str(target_level)

    prereqs = BUILDING_UPGRADE_PREREQUISITES.get(key)
    if prereqs:
        for req_type, req_level in prereqs:
            actual_level = all_building_levels.get(req_type, 0)
            if actual_level < req_level:
                return False, ("necessite batiment type " + str(req_type) +
                                " niveau " + str(req_level) +
                                " (actuellement niveau " + str(actual_level) + ")")

    cost = BUILDING_UPGRADE_COSTS.get(key)
    if cost:
        for res_type, amount_needed in cost.items():
            available = available_resources.get(res_type, 0)
            if available < amount_needed:
                return False, ("ressource insuffisante (type " + str(res_type) +
                                " : " + str(available) + "/" + str(amount_needed) + ")")

    return True, None
